"""Generate the paper's LaTeX tables directly from recorded results (no hand-typed numbers).

Usage::

    uv run python paper/make_tables.py --config configs/main.yaml

Reads the experiment of record (``experiment.name`` in the config) and the latest
``denoise_evaluation`` run record, and writes ``paper/generated/*.tex``. Each table file starts
with a comment naming its source, the commit(s) that produced the data, and the generation time.
"""

from __future__ import annotations

import argparse
import json
from collections.abc import Sequence
from datetime import UTC, datetime
from pathlib import Path

import numpy as np
import pandas as pd

from nisq_folio.analysis.noise import analyze
from nisq_folio.analysis.summary import (
    budget_table,
    classical_table,
    denoising_table,
    deployment_table,
    flatten,
    mixer_table,
)
from nisq_folio.config import load_config
from nisq_folio.experiments.store import experiment_dir, load_results

OUT = Path(__file__).resolve().parent / "generated"
MIXER_NAMES = {"x": "X", "xy_ring": "XY ring", "adapt": "ADAPT"}


def header(source: str, commits: Sequence[str]) -> str:
    """Provenance comment placed at the top of every generated table."""
    stamp = datetime.now(UTC).isoformat(timespec="seconds")
    joined = ", ".join(commits)
    return f"% Generated by paper/make_tables.py from {source}; commits {joined}; {stamp}\n"


def fmt(value: float, digits: int = 2) -> str:
    """Format a number for a table cell."""
    return (
        "--"
        if value is None or (isinstance(value, float) and np.isnan(value))
        else f"{value:.{digits}f}"
    )


def noiseless_amplification(qaoa: pd.DataFrame) -> str:
    """Median A [IQR] and share A > 1 per mixer and N (sample covariance, m = 0)."""
    q = qaoa[(qaoa["noise_level"] == 0) & (qaoa["denoising"] == "none")]
    sizes = sorted(q["n"].unique())
    rows = []
    for mixer in ("adapt", "xy_ring", "x"):
        cells = []
        for n in sizes:
            a = q[(q["mixer"] == mixer) & (q["n"] == n)]["A"]
            cells.append(
                f"{a.median():.2f} [{a.quantile(0.25):.2f}, {a.quantile(0.75):.2f}] "
                f"({100 * (a > 1).mean():.0f}\\%)"
            )
        rows.append(f"{MIXER_NAMES[mixer]} & " + " & ".join(cells) + r" \\")
    return (
        "\\begin{tabular}{l"
        + "c" * len(sizes)
        + "}\n\\toprule\n"
        + "Mixer & "
        + " & ".join(f"$N={n}$" for n in sizes)
        + r" \\"
        + "\n\\midrule\n"
        + "\n".join(rows)
        + "\n\\bottomrule\n\\end{tabular}\n"
    )


def paired_ratios(table: pd.DataFrame, label_col: str, labels: dict[str, str]) -> str:
    """Geometric-mean A ratio (share better) per row label and N."""
    sizes = sorted(table["n"].unique())
    rows = []
    for key, label in labels.items():
        sub = table[table[label_col] == key]
        cells = []
        for n in sizes:
            r = sub[sub["n"] == n]
            cells.append(
                "--"
                if r.empty
                else f"{r['ratio'].iloc[0]:.2f} ({100 * r['share_better'].iloc[0]:.0f}\\%)"
            )
        rows.append(f"{label} & " + " & ".join(cells) + r" \\")
    return (
        "\\begin{tabular}{l"
        + "c" * len(sizes)
        + "}\n\\toprule\n"
        + "Comparison & "
        + " & ".join(f"$N={n}$" for n in sizes)
        + r" \\"
        + "\n\\midrule\n"
        + "\n".join(rows)
        + "\n\\bottomrule\n\\end{tabular}\n"
    )


def classical(classical_df: pd.DataFrame) -> str:
    """Share of instances solved optimally by each classical method (sample covariance)."""
    t = classical_table(classical_df)
    t = t[t["denoising"] == "none"].sort_values("n")
    cols = [("greedy_optimal", "Greedy"), ("markowitz_optimal", "Markowitz + rounding")]
    cols += [(f"sa_{b}_optimal", f"SA, {b} steps") for b in (25, 50, 100, 200, 500, 2000)]
    rows = [
        f"{label} & " + " & ".join(f"{100 * v:.0f}\\%" for v in t[c]) + r" \\" for c, label in cols
    ]
    return (
        "\\begin{tabular}{l"
        + "c" * len(t)
        + "}\n\\toprule\n"
        + "Method & "
        + " & ".join(f"$N={n}$" for n in t["n"])
        + r" \\"
        + "\n\\midrule\n"
        + "\n".join(rows)
        + "\n\\bottomrule\n\\end{tabular}\n"
    )


def budget(qaoa: pd.DataFrame, classical_df: pd.DataFrame) -> str:
    """Median QAOA total shots per run vs SA steps for 90% optimal (sample covariance)."""
    t = budget_table(qaoa[qaoa["noise_level"] == 0], classical_df)
    t = t[t["denoising"] == "none"]
    sizes = sorted(t["N"].unique())
    rows = []
    for mixer in ("adapt", "xy_ring", "x"):
        s = t[t["mixer"] == mixer].set_index("N")["qaoa_total_shots"]
        rows.append(
            f"{MIXER_NAMES[mixer]} (shots) & " + " & ".join(f"{s[n]:,.0f}" for n in sizes) + r" \\"
        )
    sa = t.drop_duplicates("N").set_index("N")["sa_budget_90"]
    rows.append(
        "SA (steps, $\\geq 90\\%$ optimal) & " + " & ".join(f"{int(sa[n])}" for n in sizes) + r" \\"
    )
    return (
        "\\begin{tabular}{l"
        + "c" * len(sizes)
        + "}\n\\toprule\n"
        + "Method & "
        + " & ".join(f"$N={n}$" for n in sizes)
        + r" \\"
        + "\n\\midrule\n"
        + "\n".join(rows)
        + "\n\\bottomrule\n\\end{tabular}\n"
    )


def deployment(qaoa: pd.DataFrame, classical_df: pd.DataFrame) -> str:
    """Modal-optimal rate and out-of-sample variance ratio of the modal selection."""
    t = deployment_table(qaoa[qaoa["noise_level"] == 0], classical_df)
    sizes = sorted(t["n"].unique())
    rows = []
    for mixer in ("adapt", "xy_ring", "x"):
        s = t[t["mixer"] == mixer].set_index("n")
        rows.append(
            f"{MIXER_NAMES[mixer]} & "
            + " & ".join(
                f"{100 * s.loc[n, 'mode_optimal']:.0f}\\% / "
                f"{s.loc[n, 'oos_variance_ratio_median']:.2f}"
                for n in sizes
            )
            + r" \\"
        )
    return (
        "\\begin{tabular}{l"
        + "c" * len(sizes)
        + "}\n\\toprule\n"
        + "Mixer & "
        + " & ".join(f"$N={n}$" for n in sizes)
        + r" \\"
        + "\n\\midrule\n"
        + "\n".join(rows)
        + "\n\\bottomrule\n\\end{tabular}\n"
    )


def _m(value: float) -> str:
    return "$>1$" if np.isinf(value) else f"{value:.2f}"


def noise_crossover(n1: pd.DataFrame, n2: pd.DataFrame) -> str:
    """ADR-028: crossover m* [95% CI] and median A at m = 1, per mixer and complete N."""
    n1, n2 = n1[n1["denoising"] == "none"], n2[n2["denoising"] == "none"]
    sizes = sorted(n2["n"].unique())
    rows = []
    for mixer in ("adapt", "xy_ring", "x"):
        cells = []
        for n in sizes:
            c = n2[(n2["mixer"] == mixer) & (n2["n"] == n)]
            a = n1[(n1["mixer"] == mixer) & (n1["n"] == n) & (n1["noise_level"] == 1.0)]
            if c.empty:
                cells += ["--", "--"]
                continue
            r = c.iloc[0]
            cells.append(f"{_m(r['crossover'])} [{_m(r['ci_low'])}, {_m(r['ci_high'])}]")
            cells.append(fmt(a["A_median"].iloc[0]) if not a.empty else "--")
        rows.append(f"{MIXER_NAMES[mixer]} & " + " & ".join(cells) + r" \\")
    head = " & ".join(f"$m^*$ ($N={n}$) & $\\Amp(m{{=}}1)$" for n in sizes)
    return (
        "\\begin{tabular}{l"
        + "cc" * len(sizes)
        + "}\n\\toprule\n"
        + "Mixer & "
        + head
        + r" \\"
        + "\n\\midrule\n"
        + "\n".join(rows)
        + "\n\\bottomrule\n\\end{tabular}\n"
    )


def denoise_evaluation(record: dict) -> str:
    """ADR-022: rmt_clip vs sample covariance on the classical optimum, out of sample."""
    rows = []
    for n, block in sorted(record["results"]["sizes"].items(), key=lambda kv: int(kv[0])):
        inst = block["instances"]
        changed = [x for x in inst if x["rmt_clip"]["selection"] != x["sample"]["selection"]]
        lower = (
            np.mean(
                [
                    x["rmt_clip"]["realized_variance"] < x["sample"]["realized_variance"]
                    for x in changed
                ]
            )
            if changed
            else float("nan")
        )
        p = block["comparisons"]["rmt_clip"]["realized_variance"]["wilcoxon_p"]
        rows.append(
            f"{n} & {len(changed)}/{len(inst)} & {fmt(100 * lower, 0)}\\% & {p:.3g}" + r" \\"
        )
    dist = record["results"]["correlation_distance"]
    caption_note = (
        f"% correlation distance to out-of-sample: sample {dist['sample']:.3f}, "
        f"rmt_clip {dist['rmt_clip']:.3f}, ledoit_wolf {dist['ledoit_wolf']:.3f}\n"
    )
    return caption_note + (
        "\\begin{tabular}{cccc}\n\\toprule\n$N$ & Selection changed & Lower realized variance "
        "(among changed) & Wilcoxon $p$ \\\\\n\\midrule\n"
        + "\n".join(rows)
        + "\n\\bottomrule\n\\end{tabular}\n"
    )


def main(argv: Sequence[str] | None = None) -> int:
    """Write every generated table (module docstring); returns the exit code."""
    parser = argparse.ArgumentParser(prog="paper/make_tables.py")
    parser.add_argument("--config", required=True)
    args = parser.parse_args(argv)
    config = load_config(args.config)
    records = load_results(experiment_dir(config))
    commits = sorted({r["git"]["commit"][:7] for r in records if r["git"]["commit"]})
    qaoa, classical_df = flatten(records)
    source = f"results/experiments/{config.require_experiment().name}"
    OUT.mkdir(exist_ok=True)
    tables = {
        "noiseless_amplification": noiseless_amplification(qaoa),
        "mixer_ratios": paired_ratios(
            mixer_table(qaoa[qaoa["noise_level"] == 0]),
            "comparison",
            {
                "adapt / xy_ring": "ADAPT / XY ring",
                "xy_ring / x": "XY ring / X",
                "adapt / x": "ADAPT / X",
            },
        ),
        "denoising_qaoa": paired_ratios(
            denoising_table(qaoa[qaoa["noise_level"] == 0]),
            "mixer",
            {m: f"{MIXER_NAMES[m]}: RMT / sample" for m in ("adapt", "xy_ring", "x")},
        ),
        "classical": classical(classical_df),
        "budget": budget(qaoa, classical_df),
        "deployment": deployment(qaoa, classical_df),
    }
    noisy = analyze(qaoa, classical_df, config.seed)
    if not noisy["N2"].empty:
        tables["noise_crossover"] = noise_crossover(noisy["N1"], noisy["N2"])
    for name, body in tables.items():
        (OUT / f"{name}.tex").write_text(
            header(source, commits) + body, encoding="utf-8", newline="\n"
        )
    denoise_records = sorted((config.results_dir / "denoise_evaluation").glob("*.json"))
    if denoise_records:
        record = json.loads(denoise_records[-1].read_text(encoding="utf-8"))
        body = denoise_evaluation(record)
        src = f"results/denoise_evaluation/{denoise_records[-1].name}"
        (OUT / "denoise_evaluation.tex").write_text(
            header(src, [record["git"]["commit"][:7]]) + body, encoding="utf-8", newline="\n"
        )
    print(f"wrote {len(list(OUT.glob('*.tex')))} tables to {OUT}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
